"""Aggregate E1 certificate-validation grids -> summary table (paper Table 2).

Reads results/e1/*.json, groups by (problem, tier, gamma, r, K), reports:
validity, tightness quantiles (median across seeds of per-run medians),
contractive fraction, HVP cost. Writes results/e1/SUMMARY.md.
"""

from __future__ import annotations

import glob
import json
import os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
E1 = os.path.join(HERE, "..", "results", "e1")

rows = []
for path in sorted(glob.glob(os.path.join(E1, "*.json"))):
    if "SUMMARY" in path:
        continue
    with open(path) as f:
        rows.extend(json.load(f))

groups = defaultdict(list)
for r in rows:
    key = (r["problem"], r["tier"], r.get("gamma", 1.0), r["r"], r["K"])
    groups[key].append(r)

lines = [
    "# E1 Summary (auto-generated by analyze_e1.py)",
    "",
    f"Total runs: {len(rows)} | runs with any certificate violation: "
    f"{sum(1 for r in rows if r['valid_rate'] < 1.0)}",
    "",
    "| problem | tier | gamma | r | K | valid | tight med | tight p95 | "
    "contract | est HVP | KW HVP |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]
for key in sorted(groups):
    g = groups[key]
    prob, tier, gamma, r, K = key
    med = np.median([x["tight_med"] for x in g])
    p95 = np.median([x["tight_q95"] for x in g])
    valid = np.mean([x["valid_rate"] for x in g])
    contract = np.mean([x["contractive_frac"] for x in g])
    est_hvp = np.mean([x["est_hvp"] for x in g])
    kw_hvp = np.mean([x.get("kw_hvp", 0) for x in g])
    fmt = (lambda v: f"{v:.3g}" if v < 1e6 else f"{v:.1e}")
    lines.append(
        f"| {prob} | {tier} | {gamma} | {r} | {K} | {valid:.3f} | "
        f"{fmt(med)} | {fmt(p95)} | {contract:.2f} | {est_hvp:.0f} | "
        f"{kw_hvp:.0f} |")

out = os.path.join(E1, "SUMMARY.md")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines[:8]))
print(f"... ({len(lines) - 8} more rows) -> {out}")

# headline numbers for findings
best = [k for k in groups if k[0] == "teacher" and k[1] == "kw"
        and k[2] in (0.9, 0.95)]
print("\nHEADLINE teacher/kw discounted configs:")
for key in sorted(best):
    g = groups[key]
    med = np.median([x["tight_med"] for x in g])
    print(f"  gamma={key[2]} r={key[3]} K={key[4]}: tight_med={med:.3g}")
